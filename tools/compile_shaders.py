#!/usr/bin/env python3
"""
Compiles Bismuth's bgfx shaders (shaders/*.sc) for every backend and writes
embedded headers to src/gfx/shaders/generated/.

The generated headers are committed so that building the mod doesn't require
bgfx's shader compiler (shaderc) for the target platform. Re-run this script
after editing anything in shaders/.

Usage:
    python3 tools/compile_shaders.py --shaderc <path/to/shaderc> --bgfx <bgfx source dir>
    python3 tools/compile_shaders.py ... --check   # fail if generated files are stale

shaderc and the bgfx sources must come from the pinned bgfx revision
(see cmake/Bgfx.cmake); tools/build_shaderc.sh builds both.
"""

import argparse
import hashlib
import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHADER_DIR = os.path.join(ROOT, "shaders")
OUT_DIR = os.path.join(ROOT, "src", "gfx", "shaders", "generated")

# Profile name -> (shaderc --platform, shaderc -p, C identifier suffix)
PROFILES = {
    "spirv":  ("linux",   "spirv",  "spirv"),
    "metal":  ("osx",     "metal",  "metal"),
    "glsl430": ("linux",  "430",    "glsl430"),
    "glsl120": ("linux",  "120",    "glsl120"),
    "essl100": ("android", "100_es", "essl100"),
}

GPU_PROFILES = ["spirv", "metal", "glsl430"]
ALL_PROFILES = ["spirv", "metal", "glsl430", "glsl120", "essl100"]

# shader name -> (type, profiles)
SHADERS = {
    "cs_cull":           ("c", GPU_PROFILES),
    "cs_scan":           ("c", GPU_PROFILES),
    "cs_copy":           ("c", GPU_PROFILES),
    "vs_object_gpu":     ("v", GPU_PROFILES),
    "vs_object_cpu":     ("v", ALL_PROFILES),
    "fs_object":         ("f", ALL_PROFILES),
    "fs_overdraw_count": ("f", ALL_PROFILES),
    "vs_fullscreen":     ("v", ALL_PROFILES),
    "fs_overdraw_heat":  ("f", ALL_PROFILES),
}


def compile_one(shaderc, bgfx_dir, name, shader_type, profile):
    platform, shaderc_profile, suffix = PROFILES[profile]
    source = os.path.join(SHADER_DIR, name + ".sc")
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, "out.bin")
        cmd = [
            shaderc,
            "-f", source,
            "-o", out,
            "--type", shader_type,
            "--platform", platform,
            "-p", shaderc_profile,
            "-i", os.path.join(bgfx_dir, "src"),
            "-i", SHADER_DIR,
            "--varyingdef", os.path.join(SHADER_DIR, "varying.def.sc"),
        ]
        if shader_type != "c":
            cmd += ["-O", "3"]
        result = subprocess.run(cmd, capture_output=True, text=True)
        if result.returncode != 0 or not os.path.exists(out):
            sys.stderr.write(f"error: {name} [{profile}] failed:\n{result.stdout}\n{result.stderr}\n")
            return None
        with open(out, "rb") as f:
            return f.read()


def to_header(identifier, data):
    lines = [f"static const uint8_t {identifier}[{len(data)}] =", "{"]
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        lines.append("\t" + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--shaderc", required=True)
    parser.add_argument("--bgfx", required=True, help="bgfx source directory (for bgfx_shader.sh)")
    parser.add_argument("--check", action="store_true", help="only verify the generated files are up to date")
    args = parser.parse_args()

    outputs = {}
    failed = False

    for name, (shader_type, profiles) in SHADERS.items():
        for profile in profiles:
            data = compile_one(args.shaderc, args.bgfx, name, shader_type, profile)
            if data is None:
                failed = True
                continue
            suffix = PROFILES[profile][2]
            identifier = f"{name}_{suffix}"
            outputs[identifier + ".bin.h"] = (
                "// Generated by tools/compile_shaders.py from shaders/" + name + ".sc. Do not edit.\n"
                + to_header(identifier, data)
            )

    if failed:
        return 1

    # Index header: one entry per shader, null where a profile isn't compiled.
    index = [
        "// Generated by tools/compile_shaders.py. Do not edit.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "#include <cstddef>",
        "",
    ]
    for file_name in sorted(outputs):
        index.append(f'#include "{file_name}"')
    index += [
        "",
        "namespace bismuth::shaders {",
        "",
        "struct EmbeddedShader {",
        "    const char* name;",
        "    const uint8_t* spirv;   size_t spirvSize;",
        "    const uint8_t* metal;   size_t metalSize;",
        "    const uint8_t* glsl430; size_t glsl430Size;",
        "    const uint8_t* glsl120; size_t glsl120Size;",
        "    const uint8_t* essl100; size_t essl100Size;",
        "};",
        "",
        "inline constexpr EmbeddedShader kShaders[] = {",
    ]
    for name, (_, profiles) in SHADERS.items():
        fields = []
        for profile in ["spirv", "metal", "glsl430", "glsl120", "essl100"]:
            if profile in profiles:
                ident = f"{name}_{PROFILES[profile][2]}"
                fields.append(f"{ident}, sizeof({ident})")
            else:
                fields.append("nullptr, 0")
        index.append(f'    {{ "{name}", {", ".join(fields)} }},')
    index += ["};", "", "} // namespace bismuth::shaders", ""]
    outputs["shaders.hpp"] = "\n".join(index)

    stale = []
    os.makedirs(OUT_DIR, exist_ok=True)
    existing = {f for f in os.listdir(OUT_DIR)}
    for file_name, content in outputs.items():
        path = os.path.join(OUT_DIR, file_name)
        current = open(path).read() if os.path.exists(path) else None
        if current != content:
            stale.append(file_name)
            if not args.check:
                with open(path, "w", newline="\n") as f:
                    f.write(content)
    for file_name in existing - set(outputs):
        stale.append(file_name)
        if not args.check:
            os.remove(os.path.join(OUT_DIR, file_name))

    if args.check and stale:
        sys.stderr.write("Generated shaders are out of date, run tools/compile_shaders.py:\n  "
                         + "\n  ".join(stale) + "\n")
        return 1

    print(f"{len(outputs)} files {'checked' if args.check else 'written'} ({len(stale)} changed)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
